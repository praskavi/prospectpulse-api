create extension if not exists pgcrypto;

create table if not exists public.lead_runs (
  id uuid primary key default gen_random_uuid(),
  source text not null default 'n8n',
  workflow_id text,
  apify_actor text not null default 'compass~crawler-google-places',
  search_category text,
  search_city text,
  search_state text,
  search_postcodes integer[],
  max_results integer,
  raw_payload jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(),
  run_id uuid references public.lead_runs(id) on delete set null,
  company_name text not null,
  city text,
  state text,
  post_code integer,
  website text,
  phone text,
  google_url text,
  business_type text,
  rating numeric,
  review_count integer,
  research_done boolean default false,
  scraped_at timestamptz,
  apify_actor text default 'compass~crawler-google-places',
  raw_payload jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.lead_runs
  add column if not exists raw_payload jsonb;

alter table public.leads
  add column if not exists run_id uuid references public.lead_runs(id) on delete set null,
  add column if not exists state text,
  add column if not exists post_code integer,
  add column if not exists google_url text,
  add column if not exists apify_actor text default 'compass~crawler-google-places',
  add column if not exists raw_payload jsonb,
  add column if not exists updated_at timestamptz not null default now();

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_leads_updated_at on public.leads;
create trigger set_leads_updated_at
before update on public.leads
for each row
execute function public.set_updated_at();

create index if not exists idx_lead_runs_created_at on public.lead_runs(created_at desc);
create index if not exists idx_leads_run_id on public.leads(run_id);
create index if not exists idx_leads_scraped_at on public.leads(scraped_at desc);
create index if not exists idx_leads_company_city on public.leads(company_name, city);
create index if not exists idx_leads_business_type on public.leads(business_type);

create unique index if not exists uq_leads_run_company_phone_city
on public.leads (
  run_id,
  lower(company_name),
  coalesce(phone, ''),
  coalesce(city, '')
);

alter table public.lead_runs enable row level security;
alter table public.leads enable row level security;

comment on table public.lead_runs is
  'One row per n8n/Apify lead generation workflow run. Replaces Google Sheets run metadata.';

comment on table public.leads is
  'Raw leads generated by n8n from Apify Google Places. User-facing MVP1 search results can still be copied into public.search_results with 30-day retention.';

comment on column public.leads.google_url is 'Maps/place URL from the Apify Google Places actor. Matches the Google Sheet Url column.';
